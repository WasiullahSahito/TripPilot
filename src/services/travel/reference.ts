export const airportLabel = (a: Airport) => `${a.city} (${a.code})`

export function findAirport(input: string): Airport | undefined {
  const q = input.trim().toLowerCase()
  if (!q) return undefined
  return airports.find((a) => a.code.toLowerCase() === q || airportLabel(a).toLowerCase() === q || a.city.toLowerCase() === q)
}

/** Whole days between two YYYY-MM-DD strings (b - a). */
export function daysBetween(a: string, b: string) {
  const t = (d: string) => Date.UTC(+d.slice(0, 4), +d.slice(5, 7) - 1, +d.slice(8, 10))
  return Math.round((t(b) - t(a)) / 86_400_000)
}
